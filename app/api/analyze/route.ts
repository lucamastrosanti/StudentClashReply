/**
 * One request per material: the document is opened, every slide is rasterised
 * and transcribed by the vision model, and the answer is streamed as
 * newline-delimited JSON (`progress`, then one `slide` per transcription, then
 * `done` or `error`).
 *
 * Each slide carries its content Markdown plus the page furniture (headers,
 * footers, logos, page numbers, …) that was kept out of it. Once the deck is
 * done, the furniture is merged into one deck-level summary.
 *
 * Nothing is rendered back to PDF: the output of this route is the per-slide
 * Markdown itself.
 */
export const maxDuration = 300;

const MAX_FILE_BYTES = 25 * 1024 * 1024;
const MAX_SLIDES = 60;
/** Two concurrent model calls: fast enough, still gentle on rate limits. */
const CONCURRENCY = 2;
const ALLOWED_EXTENSIONS = [".pdf", ".pptx"];
/** Percentage budget: 0-10 prepares the document, 10-100 transcribes slides. */
const ANALYSIS_START = 10;

export async function POST(request: NextRequest) {
  let formData: FormData;
  try {
    formData = await request.formData();
  } catch {
    return NextResponse.json(
      { error: "The upload could not be read. Please try again." },
      { status: 400 },
    );
  }

  const file = formData.get("file");

  if (!(file instanceof File)) {
    return NextResponse.json({ error: "No file provided." }, { status: 400 });
  }
  if (file.size === 0) {
    return NextResponse.json({ error: "The uploaded file is empty." }, { status: 400 });
  }
  if (file.size > MAX_FILE_BYTES) {
    return NextResponse.json(
      { error: "File too large. The maximum supported size is 25 MB." },
      { status: 413 },
    );
  }

  const extension = path.extname(file.name).toLowerCase();
  if (extension === ".ppt") {
    return NextResponse.json(
      {
        error:
          "Legacy .ppt presentations are not supported. Save the file as .pptx (or PDF) and upload it again.",
      },
      { status: 415 },
    );
  }
  if (!ALLOWED_EXTENSIONS.includes(extension)) {
    return NextResponse.json(
      {
        error: `Unsupported file type "${extension || "unknown"}". Upload a .pdf or .pptx file.`,
      },
      { status: 415 },
    );
  }
  if (!isDescriberConfigured()) {
    return NextResponse.json(
      {
        error:
          "DEEPSEEK_API_KEY is not configured. The slide breakdown is generated by the vision model, so the key is required.",
      },
      { status: 503 },
    );
  }

  // Without this pre-flight an unusable account fails on every single slide,
  // which is exactly the "some slides are not loaded" symptom.
  const balance = await checkModelBalance();
  if (balance && !balance.available) {
    return NextResponse.json({ error: balance.message }, { status: 503 });
  }

  const buffer = Buffer.from(await file.arrayBuffer());
  const sourceName = file.name;

  const stream = new ReadableStream<Uint8Array>({
    start(controller) {
      void run({ controller, buffer, sourceName, extension });
    },
  });

  return new Response(stream, {
    headers: {
      "Content-Type": "application/x-ndjson; charset=utf-8",
      "Cache-Control": "no-store, no-transform",
      "X-Accel-Buffering": "no",
    },
  });
}

interface RunInput {
  controller: ReadableStreamDefaultController<Uint8Array>;
  buffer: Buffer;
  sourceName: string;
  extension: string;
}

async function run(input: RunInput): Promise<void> {
  const { controller, buffer, sourceName, extension } = input;
  const encoder = new TextEncoder();
  let closed = false;

  const send = (event: AnalysisStreamEvent): void => {
    if (closed) return;

    try {
      controller.enqueue(encoder.encode(`${JSON.stringify(event)}\n`));
    } catch {
      // The browser went away: stop writing, the work is simply abandoned.
      closed = true;
    }
  };

  const progress = (stage: AnalysisStage, value: number, message: string, total?: number): void => {
    send({ type: "progress", stage, value, message, total });
  };

  let workDir: string | null = null;

  try {
    progress("queued", 2, "Preparing the document…");

    let pdfBuffer = buffer;
    let sourceType: SourceType = "pdf";
    let converter: "libreoffice" | "powerpoint" | null = null;

    if (extension === ".pptx") {
      workDir = await fs.mkdtemp(path.join(os.tmpdir(), "studentclash-"));
      progress("converting", 5, "Converting the presentation to PDF…");
      const converted = await convertPptxToPdf(buffer, workDir);
      pdfBuffer = converted.pdf;
      sourceType = "pptx";
      converter = converted.converter;
      progress("converting", ANALYSIS_START, "Presentation converted to PDF.");
    } else {
      progress("rendering", ANALYSIS_START, "Opening the PDF…");
    }

    const pages = await openPdfPages(pdfBuffer);

    try {
      await transcribePages({
        pages,
        sourceName,
        sourceType,
        converter,
        send,
        progress,
        isClosed: () => closed,
      });
    } finally {
      await pages.close();
    }
  } catch (error) {
    send({
      type: "error",
      message: error instanceof Error ? error.message : "An unexpected error occurred.",
    });
  } finally {
    closed = true;

    try {
      controller.close();
    } catch {
      // Already closed by the client.
    }

    if (workDir) {
      await fs.rm(workDir, { recursive: true, force: true }).catch(() => undefined);
    }
  }
}

interface TranscribeInput {
  pages: PdfPages;
  sourceName: string;
  sourceType: SourceType;
  converter: "libreoffice" | "powerpoint" | null;
  send: (event: AnalysisStreamEvent) => void;
  progress: (stage: AnalysisStage, value: number, message: string, total?: number) => void;
  isClosed: () => boolean;
}

/** Rasterises and transcribes every page, at most `CONCURRENCY` at a time. */
async function transcribePages(input: TranscribeInput): Promise<void> {
  const { pages, sourceName, sourceType, converter, send, progress, isClosed } = input;

  const total = Math.min(pages.pageCount, MAX_SLIDES);
  if (total === 0) throw new Error("The document contains no pages.");

  const truncated = pages.pageCount > MAX_SLIDES;
  const slides: SlideAnalysis[] = [];
  let next = 0;
  let completed = 0;
  let fatal: Error | null = null;

  progress(
    "analyzing",
    ANALYSIS_START,
    total === 1 ? "Analysing 1 slide…" : `Analysing ${total} slides…`,
    total,
  );

  const worker = async (): Promise<void> => {
    for (;;) {
      if (fatal || isClosed()) return;

      const index = next;
      next += 1;
      if (index >= total) return;

      const pageNumber = index + 1;
      let page: PageImage | null = null;

      try {
        page = await pages.page(pageNumber);

        if (!page) {
          const slide = failedSlide(pageNumber, total, "the page could not be rendered");
          slides.push(slide);
          send({ type: "slide", slide });
          continue;
        }

        const image = await page.snapshot();
        const thumbnail = await page.thumbnail();
        const description = await describeSlide({ image, index: pageNumber, total });

        const slide: SlideAnalysis = {
          index: pageNumber,
          total,
          thumbnail,
          markdown: description.markdown,
          figures: description.figures,
          layout: description.layout,
          usedAI: description.usedAI,
        };

        // Each figure travels to the rebuild with its own picture and, when the
        // document has a text layer, with its exact texts. Rendering the figure
        // again from the vector page is what makes a table or a code panel
        // readable: inside the page raster it would be a hundred pixels wide.
        if (description.figures.length > 0) {
          const figureCrops: Record<string, string> = {};
          let cropChars = 0;

          for (const figure of description.figures) {
            // The reported area is a little tight: it is widened once, here,
            // and that box is the one the rebuild will use, so crop, layout
            // and review all look at exactly the same rectangle.
            let box = expandBox(figure.box);
            figure.box = box;

            try {
              // Look for text a little outside the box too: the header of a
              // table often sits just above the area the model drew. When the
              // document has a text layer, its bounds refine the box; a table
              // is defined by its text, so for a table they replace it.
              const probe = inflateBox(box, 0.035);
              const texts = await page.textsIn(probe);
              const bounds = await page.textBoundsIn(probe);

              if (bounds) {
                box =
                  figure.kind === "table"
                    ? expandBox(bounds, 0.04)
                    : expandBox(unionBoxes(box, bounds), 0.02);
                figure.box = box;
              }

              if (texts.length > 0) figure.verbatim = texts;

              const crop = await page.crop(box);
              if (crop && cropChars + crop.length <= 2_400_000) {
                figureCrops[figure.id] = crop;
                cropChars += crop.length;
              }
            } catch (error) {
              console.warn(
                `Slide ${pageNumber}, figure ${figure.id}: the element could not be prepared (${
                  error instanceof Error ? error.message : "unknown error"
                }).`,
              );
            }
          }

          if (Object.keys(figureCrops).length > 0) slide.figureCrops = figureCrops;
        }

        slides.push(slide);
        send({ type: "slide", slide });
      } catch (error) {
        if (error instanceof DescriberError && error.fatal) {
          fatal = error;
          return;
        }

        const message = error instanceof Error ? error.message : "unknown error";
        const slide = failedSlide(pageNumber, total, message);
        slides.push(slide);
        send({ type: "slide", slide });
      } finally {
        completed += 1;
        page?.dispose();

        const value = ANALYSIS_START + Math.round((completed / total) * (100 - ANALYSIS_START));
        progress(
          "analyzing",
          Math.min(99, value),
          `Slide ${Math.min(completed, total)} of ${total} processed.`,
        );
      }
    }
  };

  await Promise.all(Array.from({ length: Math.min(CONCURRENCY, total) }, () => worker()));

  if (fatal) throw fatal;
  if (isClosed()) return;

  slides.sort((a, b) => a.index - b.index);

  const aiSlides = slides.filter((slide) => slide.usedAI).length;
  const failedSlides = slides.length - aiSlides;

  // A per-slide call cannot see the repetitions: merge the furniture found on
  // every slide here, then let a text-only pass name the patterns.
  const findings = collectLayoutFindings(slides);
  let layoutMarkdown: string | null = null;

  if (findings.length > 0) {
    progress("analyzing", 99, "Summarising the layout elements…");
    layoutMarkdown = await refineLayoutSummary({ fileName: sourceName, findings });
  }

  const layout: LayoutSummary = {
    markdown: layoutMarkdown ?? renderLayoutMarkdown(findings, slides.length),
    findings,
    usedAI: layoutMarkdown !== null,
  };

  const highlights = buildHighlights({
    slides: slides.length,
    failedSlides,
    sourceType,
    truncated,
    converter,
  });

  if (findings.length > 0) {
    highlights.push(
      `${findings.length} recurring or marginal layout elements were kept out of the transcriptions.`,
    );
  }

  const result: AnalysisResult = {
    status: "success",
    message: `${slides.length} slides transcribed.`,
    stats: { slides: slides.length, aiSlides, failedSlides, sourceType, truncated },
    layout,
    highlights,
  };

  progress("completed", 100, "Slide breakdown ready.");
  send({ type: "done", result });
}

function failedSlide(index: number, total: number, reason: string): SlideAnalysis {
  return {
    index,
    total,
    thumbnail: "",
    markdown: `# Slide ${index}\n\n> The description is not available: ${reason}`,
    figures: [],
    layout: [],
    usedAI: false,
    note: reason,
  };
}

interface HighlightInput {
  slides: number;
  failedSlides: number;
  sourceType: SourceType;
  truncated: boolean;
  converter: "libreoffice" | "powerpoint" | null;
}

function buildHighlights(input: HighlightInput): string[] {
  const highlights = [
    `${input.slides} slides transcribed from ${
      input.sourceType === "pptx" ? "PowerPoint" : "PDF"
    }.`,
    "Content transcribed verbatim; headers, footers, logos and page numbers kept out.",
  ];

  if (input.converter === "powerpoint") {
    highlights.push("PPTX converted to PDF with PowerPoint.");
  }
  if (input.converter === "libreoffice") {
    highlights.push("PPTX converted to PDF with LibreOffice.");
  }
  if (input.truncated) {
    highlights.push(`Only the first ${MAX_SLIDES} slides were analysed.`);
  }
  if (input.failedSlides > 0) {
    highlights.push(`${input.failedSlides} slides could not be described.`);
  }

  return highlights;
}


